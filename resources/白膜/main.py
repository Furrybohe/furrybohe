def rot_mat(x, y, z, m):
    return f'''
"v.cy = math.cos({x});",
"v.sy = math.sin({x});",
"v.cb = math.cos({y});",
"v.sb = math.sin({y});",
"v.ca = math.cos({z});",
"v.sa = math.sin({z});",

"v.{m}_00 = v.ca * v.cb;",
"v.{m}_01 = v.ca * v.sb * v.sy - v.sa * v.cy;",
"v.{m}_02 = v.ca * v.sb * v.cy + v.sa * v.sy;",
"v.{m}_03 = 0;",

"v.{m}_10 = v.sa * v.cb;",
"v.{m}_11 = v.sa * v.sb * v.sy + v.ca * v.cy;",
"v.{m}_12 = v.sa * v.sb * v.cy - v.ca * v.sy;",
"v.{m}_13 = 0;",

"v.{m}_20 = -v.sb;",
"v.{m}_21 = v.cb * v.sy;",
"v.{m}_22 = v.cb * v.cy;",
"v.{m}_23 = 0;",

"v.{m}_30 = 0;",
"v.{m}_31 = 0;",
"v.{m}_32 = 0;",
"v.{m}_33 = 1;",
'''

def rot_mat_inv(m):
    return f'''
"v.t = v.{m}_01;",
"v.{m}_01 = v.{m}_10;",
"v.{m}_10 = v.t;",
"v.t = v.{m}_02;",
"v.{m}_02 = v.{m}_20;",
"v.{m}_20 = v.t;",
"v.t = v.{m}_12;",
"v.{m}_12 = v.{m}_21;",
"v.{m}_21 = v.t;",
'''

def trans_mat(x, y, z, m):
    return f'''
"v.{m}_00 = 1;",
"v.{m}_01 = 0;",
"v.{m}_02 = 0;",
"v.{m}_03 = {x};",

"v.{m}_10 = 0;",
"v.{m}_11 = 1;",
"v.{m}_12 = 0;",
"v.{m}_13 = {y};",

"v.{m}_20 = 0;",
"v.{m}_21 = 0;",
"v.{m}_22 = 1;",
"v.{m}_23 = {z};",

"v.{m}_30 = 0;",
"v.{m}_31 = 0;",
"v.{m}_32 = 0;",
"v.{m}_33 = 1;",
'''

def trans_mat_inv(m):
    return f'''
"v.{m}_03 = -v.{m}_03;",
"v.{m}_13 = -v.{m}_13;",
"v.{m}_23 = -v.{m}_23;",
'''

def mat_mul(m, m0, m1):
    s = ""
    for i in range(4):
        for j in range(4):
            s += f'"v.{m1}_{i}{j} = v.{m}_{i}0 * v.{m0}_0{j}'
            for k in range(1, 4):
                s += f' + v.{m}_{i}{k} * v.{m0}_{k}{j}'
            s += ';",\n'
    return s

def mat_mulv_(m, v, v0, t):
    s = ""
    for i in range(3):
        s += f'"{v0[i]} = v.{m}_{i}0 * {v[0]}'
        for j in range(1, 3 + t):
            s += f' + v.{m}_{i}{j} * {v[j]}'
        s += ';",\n'
    return s

def mat_mulv(m, v, v0, t):
    return mat_mulv_(m, v, [f'v.{v0}_x', f'v.{v0}_y', f'v.{v0}_z'], t)

